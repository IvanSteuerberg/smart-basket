"""Persistence of the agent trace: one row per run and one per step (ADR 0022).

The trace is the evaluation data set and the defence evidence, so every field of a step is
kept: the observation, the candidates the harness offered, the chosen action and its
arguments, the confidence, the result and the latency. A run stores the state needed to
resume it after a pause (`waiting_shopper`).
"""

import json
from dataclasses import dataclass
from datetime import datetime
from typing import Any
from uuid import UUID

from sqlalchemy import text
from sqlalchemy.orm import Session

#: Statuses the `agent_run.status` check constraint accepts.
RUN_STATUSES = frozenset({"running", "waiting_shopper", "completed", "failed", "timed_out"})


@dataclass(frozen=True, slots=True)
class AgentStepRow:
    """One step of a run, as stored, with its JSONB fields already decoded."""

    id: int
    run_id: UUID
    step_number: int
    observation_json: dict[str, Any]
    candidates_json: list[dict[str, Any]]
    chosen_action: str
    action_args_json: dict[str, Any]
    confidence: float | None
    probabilities_json: dict[str, float] | None
    retries: int
    used_default: bool
    result_json: dict[str, Any]
    latency_ms: int
    error: str | None
    created_at: datetime


@dataclass(frozen=True, slots=True)
class AgentRunRow:
    """One run and all its steps, ordered by `step_number`."""

    id: UUID
    agent_name: str
    recommendation_id: UUID | None
    state_json: dict[str, Any]
    status: str
    policy_name: str
    model_name: str | None
    steps_count: int
    total_latency_ms: int
    created_at: datetime
    updated_at: datetime
    finished_at: datetime | None
    steps: tuple[AgentStepRow, ...] = ()


def create_run(
    session: Session,
    *,
    agent_name: str,
    policy_name: str,
    model_name: str | None = None,
    recommendation_id: UUID | None = None,
    state_json: dict[str, Any] | None = None,
    status: str = "running",
) -> UUID:
    """Insert a run and return its UUIDv7, generated by the database default."""
    return session.execute(
        text(
            "insert into agent_run (agent_name, recommendation_id, state_json, status, "
            "policy_name, model_name) values (:agent_name, :recommendation_id, "
            "cast(:state as jsonb), :status, :policy_name, :model_name) returning id"
        ),
        {
            "agent_name": agent_name,
            "recommendation_id": recommendation_id,
            "state": json.dumps(state_json or {}, ensure_ascii=False),
            "status": status,
            "policy_name": policy_name,
            "model_name": model_name,
        },
    ).scalar_one()


def update_run(
    session: Session,
    run_id: UUID,
    *,
    state_json: dict[str, Any] | None = None,
    status: str | None = None,
    steps_count: int | None = None,
    total_latency_ms: int | None = None,
    finished_at: datetime | None = None,
) -> None:
    """Update the given fields of a run and always refresh `updated_at`."""
    assignments = ["updated_at = now()"]
    params: dict[str, Any] = {"run_id": run_id}
    if state_json is not None:
        assignments.append("state_json = cast(:state as jsonb)")
        params["state"] = json.dumps(state_json, ensure_ascii=False)
    if status is not None:
        assignments.append("status = :status")
        params["status"] = status
    if steps_count is not None:
        assignments.append("steps_count = :steps_count")
        params["steps_count"] = steps_count
    if total_latency_ms is not None:
        assignments.append("total_latency_ms = :total_latency_ms")
        params["total_latency_ms"] = total_latency_ms
    if finished_at is not None:
        assignments.append("finished_at = :finished_at")
        params["finished_at"] = finished_at
    session.execute(
        text(f"update agent_run set {', '.join(assignments)} where id = :run_id"), params
    )


def append_step(
    session: Session,
    *,
    run_id: UUID,
    step_number: int,
    observation_json: dict[str, Any],
    candidates_json: list[dict[str, Any]],
    chosen_action: str,
    action_args_json: dict[str, Any] | None = None,
    confidence: float | None = None,
    probabilities_json: dict[str, float] | None = None,
    retries: int = 0,
    used_default: bool = False,
    result_json: dict[str, Any] | None = None,
    latency_ms: int = 0,
    error: str | None = None,
) -> int:
    """Append one step to a run and return its identity."""
    return session.execute(
        text(
            "insert into agent_step (run_id, step_number, observation_json, candidates_json, "
            "chosen_action, action_args_json, confidence, probabilities_json, retries, "
            "used_default, result_json, latency_ms, error) values (:run_id, :step_number, "
            "cast(:observation as jsonb), cast(:candidates as jsonb), :chosen_action, "
            "cast(:action_args as jsonb), :confidence, cast(:probabilities as jsonb), "
            ":retries, :used_default, cast(:result as jsonb), :latency_ms, :error) returning id"
        ),
        {
            "run_id": run_id,
            "step_number": step_number,
            "observation": json.dumps(observation_json, ensure_ascii=False),
            "candidates": json.dumps(candidates_json, ensure_ascii=False),
            "chosen_action": chosen_action,
            "action_args": json.dumps(action_args_json or {}, ensure_ascii=False),
            "confidence": confidence,
            "probabilities": (
                None
                if probabilities_json is None
                else json.dumps(probabilities_json, ensure_ascii=False)
            ),
            "retries": retries,
            "used_default": used_default,
            "result": json.dumps(result_json or {}, ensure_ascii=False),
            "latency_ms": latency_ms,
            "error": error,
        },
    ).scalar_one()


def get_run(session: Session, run_id: UUID) -> AgentRunRow | None:
    """Fetch a run and all its steps ordered by `step_number`; `None` if it does not exist."""
    row = session.execute(
        text(
            "select id, agent_name, recommendation_id, state_json, status, policy_name, "
            "model_name, steps_count, total_latency_ms, created_at, updated_at, finished_at "
            "from agent_run where id = :run_id"
        ),
        {"run_id": run_id},
    ).one_or_none()
    if row is None:
        return None
    steps = session.execute(
        text(
            "select id, run_id, step_number, observation_json, candidates_json, chosen_action, "
            "action_args_json, confidence, probabilities_json, retries, used_default, "
            "result_json, latency_ms, error, created_at from agent_step where run_id = :run_id "
            "order by step_number asc"
        ),
        {"run_id": run_id},
    ).all()
    return AgentRunRow(
        id=row.id,
        agent_name=row.agent_name,
        recommendation_id=row.recommendation_id,
        state_json=row.state_json,
        status=row.status,
        policy_name=row.policy_name,
        model_name=row.model_name,
        steps_count=row.steps_count,
        total_latency_ms=row.total_latency_ms,
        created_at=row.created_at,
        updated_at=row.updated_at,
        finished_at=row.finished_at,
        steps=tuple(
            AgentStepRow(
                id=step.id,
                run_id=step.run_id,
                step_number=step.step_number,
                observation_json=step.observation_json,
                candidates_json=step.candidates_json,
                chosen_action=step.chosen_action,
                action_args_json=step.action_args_json,
                confidence=step.confidence,
                probabilities_json=step.probabilities_json,
                retries=step.retries,
                used_default=step.used_default,
                result_json=step.result_json,
                latency_ms=step.latency_ms,
                error=step.error,
                created_at=step.created_at,
            )
            for step in steps
        ),
    )
